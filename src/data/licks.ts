// Lick library. Frets are written as offsets from the minor-pentatonic box-1 root
// on the low E string, so every lick can be transposed to any key.
// strings: 0 = low E, 1 = A, 2 = D, 3 = G, 4 = B, 5 = high e

// b = full bend, hb = half bend, qb = quarter-bend "curl", bv = full bend held with vibrato,
// r = release from a full bend, hr = release from a half bend, pb = pre-bend (bend before picking) and release
export type Technique = 'b' | 'hb' | 'qb' | 'bv' | 'r' | 'hr' | 'pb' | 'h' | 'p' | 's' | 'v';

export interface LickNote {
  s: number; // string
  f: number; // fret offset from root fret
  d: number; // duration in beats
  t?: Technique; // technique arriving at / applied to this note
  x?: Array<[number, number]>; // extra simultaneous notes [string, fretOffset]
  rest?: boolean;
}

export interface Lick {
  id: string;
  name: string;
  level: 1 | 2 | 3 | 4;
  tonality: 'minor' | 'major'; // major licks are written in the relative-minor box
  box: number; // 1-5 (or 0 for "BB box" / extended)
  style: string;
  bpm: number;
  notes: LickNote[];
  description: string;
  tips: string[];
  function: 'opener' | 'middle' | 'ending' | 'any';
  vibes: Vibe[]; // the feel(s) this lick fits — first one is the main vibe
}

export type Vibe = 'soulful' | 'bluesy' | 'rock' | 'sweet' | 'smooth';

export interface VibeInfo {
  label: string;
  short: string; // badge text
  emoji: string;
  description: string;
  // suggested built-in backing progression for each kind of scale
  backing: { minor: string; major: string; blues: string };
}

