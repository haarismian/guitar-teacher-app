export const TECHNIQUE_LABEL: Record<Technique, string> = {
  b: 'full bend',
  hb: 'half bend',
  r: 'release',
  h: 'hammer-on',
  p: 'pull-off',
  s: 'slide',
  v: 'vibrato',
};

/** Total length in beats */
export function lickBeats(l: Lick): number {
  return l.notes.reduce((a, n) => a + n.d, 0);
}
